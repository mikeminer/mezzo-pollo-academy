import { build } from 'esbuild';
import { mkdir, copyFile, writeFile, readFile, readdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const root = resolve(import.meta.dirname, '..');
await mkdir(join(root, 'vendor'), { recursive: true });
const result = await build({
  // These are the original classes shipped by the pinned package. Importing
  // their sources excludes the unrelated CommonJS RPC client from the bundle.
  stdin: { contents: "export { Message } from '@solana/web3.js/src/message/legacy.ts'; export { Transaction } from '@solana/web3.js/src/transaction/legacy.ts';", resolveDir: root, sourcefile: 'solana-transaction-entry.mjs' },
  outfile: join(root, 'vendor/solana-transaction.mjs'), bundle: true, format: 'esm', platform: 'browser', target: ['es2022'], minify: true,
  legalComments: 'eof', sourcemap: false, metafile: true,
  banner: { js: '/* Official @solana/web3.js 1.99.0 transaction classes; generated by scripts/build-transaction.mjs. */' },
});
await copyFile(join(root, 'node_modules/@solana/web3.js/LICENSE'), join(root, 'vendor/SOLANA-WEB3-LICENSE.txt'));
const inputs = Object.keys(result.metafile.inputs).filter(name => Object.values(result.metafile.outputs).some(output => (output.inputs[name]?.bytesInOutput || 0) > 0));
await writeFile(join(root, 'vendor/solana-transaction-build.json'), JSON.stringify({ package: '@solana/web3.js', version: '1.99.0', inputs }, null, 2) + '\n');
const packages = new Set(inputs.filter(name => !name.startsWith('(disabled):')).map(name => name.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)(?:\/|$)/)?.[1]).filter(Boolean));
const notices = [];
for (const directory of [...packages].sort()) {
  for (const filename of await readdir(join(root, directory))) {
    if (/^(license|licence|copying)([._-]|$)/i.test(filename)) notices.push(`${directory}/${filename}\n\n${await readFile(join(root, directory, filename), 'utf8')}`);
  }
}
await writeFile(join(root, 'vendor/SOLANA-TRANSACTION-LICENSES.txt'), notices.join('\n\n--------------------\n\n'));
console.log('Pinned Solana transaction classes bundled for same-origin Phantom use.');
