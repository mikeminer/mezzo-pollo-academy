import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const root = resolve(import.meta.dirname, '..');
await mkdir(join(root, 'vendor'), { recursive: true });
await build({
  stdin: { contents: "export { transact } from '@solana-mobile/mobile-wallet-adapter-protocol';", resolveDir: root, sourcefile: 'mwa-entry.mjs' },
  outfile: join(root, 'vendor/mwa.mjs'), bundle: true, format: 'esm', platform: 'browser', target: ['es2022'], minify: true,
  legalComments: 'eof', sourcemap: false,
  banner: { js: '/* Official @solana-mobile/mobile-wallet-adapter-protocol 3.0.1; generated by scripts/build-wallet.mjs. */' },
});
await copyFile(join(root, 'node_modules/@solana-mobile/mobile-wallet-adapter-protocol/LICENSE'), join(root, 'vendor/MWA-LICENSE.txt'));
console.log('Pinned Mobile Wallet Adapter bundled for same-origin browser use.');
